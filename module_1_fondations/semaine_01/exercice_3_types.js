// En JavaScript, il y a plusieurs types de valeurs :
//
// - string (texte)   → entre guillemets : "Bonjour" ou 'Bonjour'
// - number (nombre)  → sans guillemets : 42, 3.14, -5
// - boolean          → true (vrai) ou false (faux)
//
// typeof permet de connaître le type d'une variable.
//
// ═══════════════════════════════════════════════════════════════════

// 3.1 Crée une variable "monTexte" avec un texte de ton choix
let monTexte;  // Exemple : let monTexte = "Minecraft";
console.log("monTexte =", monTexte);
console.log("Type :", typeof monTexte);  // Doit afficher : string

console.log("---");

// 3.2 Crée une variable "monNombre" avec un nombre de ton choix
let monNombre;  // Exemple : let monNombre = 64;
console.log("monNombre =", monNombre);
console.log("Type :", typeof monNombre);  // Doit afficher : number

console.log("---");

// 3.3 Crée une variable "monBooleen" avec true ou false
let monBooleen;  // Exemple : let monBooleen = true;
console.log("monBooleen =", monBooleen);
console.log("Type :", typeof monBooleen);  // Doit afficher : boolean

console.log("---");

